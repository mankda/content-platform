import { Octokit } from '@octokit/rest'
import { config } from 'dotenv'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
config({ path: resolve(__dirname, '../.env.local') })

const ORG   = process.env.GITHUB_ORG
const REPO  = process.env.GITHUB_REPO
const TOKEN = process.env.GITHUB_TOKEN
const APP_URL = process.env.NEXT_PUBLIC_APP_URL ?? 'http://localhost:3000'

const slug = process.argv[2]
if (!slug) { console.error('Usage: node scaffold-existing-project.mjs <slug>'); process.exit(1) }

const octokit = new Octokit({ auth: TOKEN })

async function commit(path, content) {
  // Check if file already exists so we can pass the sha
  let sha
  try {
    const { data } = await octokit.repos.getContent({ owner: ORG, repo: REPO, path })
    if (!Array.isArray(data)) sha = data.sha
  } catch {}

  await octokit.repos.createOrUpdateFileContents({
    owner: ORG,
    repo: REPO,
    path,
    message: `chore: add docusaurus scaffold to ${slug}`,
    content: Buffer.from(content).toString('base64'),
    branch: 'main',
    ...(sha ? { sha } : {}),
  })
  console.log(`  committed ${path}`)
}

const files = [
  {
    path: `projects/${slug}/package.json`,
    content: JSON.stringify({
      name: slug,
      version: '0.0.1',
      private: true,
      scripts: { build: 'docusaurus build' },
      overrides: { webpack: '5.105.0' },
      dependencies: {
        '@docusaurus/core': '3.10.0',
        '@docusaurus/preset-classic': '3.10.0',
        clsx: '2.1.1',
        react: '19.0.0',
        'react-dom': '19.0.0',
      },
    }, null, 2) + '\n',
  },
  {
    path: `projects/${slug}/docusaurus.config.js`,
    content: `// @ts-check\n\n/** @type {import('@docusaurus/types').Config} */\nconst config = {\n  title: '${slug}',\n  url: '${APP_URL}',\n  baseUrl: '/docs/${slug}/',\n  onBrokenLinks: 'warn',\n  onBrokenMarkdownLinks: 'warn',\n  trailingSlash: false,\n  presets: [\n    [\n      'classic',\n      /** @type {import('@docusaurus/preset-classic').Options} */\n      ({\n        docs: {\n          routeBasePath: '/',\n          sidebarPath: require.resolve('./sidebars.js'),\n        },\n        blog: false,\n      }),\n    ],\n  ],\n};\n\nmodule.exports = config;\n`,
  },
  {
    path: `projects/${slug}/sidebars.js`,
    content: `/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */\nconst sidebars = {\n  docs: [{ type: 'autogenerated', dirName: '.' }],\n};\n\nmodule.exports = sidebars;\n`,
  },
  {
    path: `projects/${slug}/.gitignore`,
    content: `.docusaurus\nnode_modules\nbuild\n`,
  },
]

console.log(`Scaffolding Docusaurus files for "${slug}"...`)
for (const file of files) {
  await commit(file.path, file.content)
}
console.log('Done.')
